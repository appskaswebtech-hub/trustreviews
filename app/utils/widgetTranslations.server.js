// Full translation tables for the storefront widgets (review form, Q&A, reviews grid/slider).
// These live server-side (not inside the theme app extension) because Shopify caps
// total Liquid content per extension at 100 KB — shipping 15 languages x 3 widgets
// inline would blow that budget. The liquid blocks fetch the resolved language's
// object at runtime via /apps/review instead of bundling every language.

// Languages we ship full translation tables for. Shared by every loader that
// needs to turn a Shopify locale (storefront language switcher) or a
// merchant-configured default into one of our supported language keys.
export const SUPPORTED_LANGS = ["en", "hi", "es", "fr", "de", "it", "pt", "nl", "ar", "zh", "ja", "ru", "tr", "pl", "ko"];

// Prefers the storefront's current locale (e.g. from request.locale.iso_code)
// over the merchant's saved default so widgets follow the customer's language
// switcher; falls back to the saved default, then English.
export function resolveLanguage(requestedLocale, fallback = "en") {
  if (requestedLocale) {
    const base = String(requestedLocale).split("-")[0].toLowerCase();
    if (SUPPORTED_LANGS.includes(base)) return base;
  }
  return fallback || "en";
}

